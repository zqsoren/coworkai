"""
个人持仓管理（Portfolio Manager）技能
通过在 Tool Description 中注入强大的意图识别 Prompt，赋予智能体精确访问、询问和更新本地持仓文件的能力。
"""

import json

SKILL_NAME = "portfolio_manager"

# 这里的 Description 是该技能的核心，它会被完整喂给大语言模型的 System Prompt，
# 从而强迫大模型在遇到相关意图时触发此工具，而遇到闲聊时不触发。
SKILL_DESCRIPTION = """
【核心触发规则与纪律】个人持仓管理技能。
作为专业的金融专家，在与用户对话时，你必须严格遵守以下四象限意图识别规则：

1. 宏观或大盘查询类（无需持仓信息）
   - 情景：用户询问大盘走势、宏观经济事件、个股百科、历史表现等（如：“今天A股怎么了”、“特斯拉财报如何”）。
   - 纪律：【绝对不要】使用本工具，也【绝对不要】反问用户的持仓情况！直接用你的知识回答。

2. 闲聊或通用金融知识类（无需持仓信息）
   - 情景：用户询问技术指标百科、打招呼等（如：“什么是MACD”、“你好”）。
   - 纪律：直接回答，【绝对不要】询问持仓。

3. 个人操作建议与买卖决策类（必须知道持仓细节才能回答）
   - 情景：用户寻求直接的操作建议（如：“我现在要不要割肉”、“我这10万块怎么建仓”、“帮我看看我的组合”）。
   - 纪律：你必须调用本工具读取 `持仓情况.md`。如果本工具返回文件不存在或信息不全，你必须【主动暂停提供建议】，并回复类似：“为了给您提供准确的加减仓或资产配置建议，我需要先了解您的当前资金规模和持仓明细（或者您可以直接授权我更新您的持仓文档）”。

4. 主动更新/记录持仓类（触发文件更新）
   - 情景：用户主动进行记录（如：“我今天买入了100股苹果”、“帮我记一下，我清仓了腾讯”）。
   - 纪律：直接调用本工具的 `action="update"` 功能，将相关记录指令发送给本工具，然后回复用户“已为您更新持仓记录”。

使用方法：
本工具接收 JSON 字符串格式的参数。包含 `action` 字段：
- {"action": "read"} -> 读取当前工作区下的 `持仓情况.md`。
- {"action": "update", "content": "新的持仓文本/用户的操作指令"} -> 将新的操作指令或文本覆盖/追加到 `持仓情况.md`。
"""


def run(action: str = "read", content: str = "", **kwargs) -> str:
    """
    执行持仓管理
    由于大模型通常只能获得简单的 kwargs 注入，此处的实际文件读写，
    建议让大模型知晓去调用其自带的 `read_file` 和 `write_file` 工具更为稳妥。
    但为了简化大模型的调用链路，此工具自己实现一套虚拟的返回逻辑，指导大模型。
    """
    
    # 实际上，在目前的 AgentOS 架构中，这个 Skill 在被调用时并不能轻易获取上下文关联的工作区路径
    # （因为 sl.skills 注册时是全局的）。
    # 所以最优雅的办法是：这个工具被调用时，返回一个强指导性的 Prompt，
    # 引导大模型去调用已经绑定了上下文路径的 `read_file("持仓情况.md")` 和 `write_file("持仓情况.md")`。
    
    if action == "read":
        return (
            "【Skill 返回指令】\n"
            "您已经触发了持仓读取逻辑。\n"
            "为了真正读取或创建该文件，请您立即调用您的系统内置工具 `read_file`，"
            "参数 path 填写为 `持仓情况.md`。\n"
            "如果 `read_file` 返回错误（说明文件不存在），"
            "请您立即用自然语言询问用户当前的持仓和资金状况，以便记录。"
        )
    elif action == "update":
        return (
            "【Skill 返回指令】\n"
            "您已经触发了持仓更新逻辑。待更新的内容或指令是：\n"
            f"{content}\n\n"
            "请您立即调用系统内置工具 `write_file`，参数 path 填写为 `持仓情况.md`，"
            "并将您整理好的最新持仓 Markdown 表格作为 content 写入。\n"
            "完成后，请告诉用户已更新。"
        )
    
    return "动作无效。请使用 action='read' 或 action='update'。"
